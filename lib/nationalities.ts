export type NationalityCode = typeof NATIONALITIES[number]['code']
export type NationalityName = typeof NATIONALITIES[number]['name']

export function getNationalityByCode(code: string): typeof NATIONALITIES[number] | undefined {
  return NATIONALITIES.find(n => n.code === code || n.name.toLowerCase() === code.toLowerCase())
}

export function getNationalityByName(name: string): typeof NATIONALITIES[number] | undefined {
  return NATIONALITIES.find(n => n.name.toLowerCase() === name.toLowerCase())
}

export function getNationalityFlag(name: string): string {
  const nationality = getNationalityByName(name)
  return nationality?.flag || ''
}

